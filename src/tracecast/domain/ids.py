"""Stable id derivation and call-local alias helpers.

Two distinct concerns live here:

1. **Stable global ids** -- deterministic, persisted, generated by code (never by
   the model). Inputs deliberately exclude volatile semantic labels
   (``content_kind``, ``narrative_function``, ``summary``, ``tags``) so those
   labels can evolve without changing an artifact's identity.

   ``piece_id`` uses ``"{source_id}:{order_index:06d}"`` (for example
   ``src:000123``). Everywhere else the
   id is ``"{prefix}_{sha256(canonical_inputs)[:16]}"`` -- a deterministic,
   collision-resistant scheme documented per function.

2. **Call-local aliases** -- short, human-readable handles (``p0001``, ``M001``,
   ``C001``, ``N1``, ``R001``) valid only within a single projection/call.
   :class:`AliasManifest` mints them in projection order and resolves them back to
   global ids; ``resolve`` raises on unknown/malformed aliases (fail-and-report,
   never silently invent an id).

``call_id`` is the one non-deterministic id: every provider attempt receives a
fresh id, so :func:`new_call_id` is uuid-based by design.
"""

from __future__ import annotations

import hashlib
import uuid
from collections.abc import Iterable
from dataclasses import dataclass

_FIELD_SEP = "\x1f"
_LIST_SEP = "\x1e"
_DIGEST_LEN = 16


def _canonical(part: object) -> str:
    if isinstance(part, (list, tuple)):
        return _LIST_SEP.join(str(item) for item in part)
    return str(part)


def _digest(*parts: object, length: int = _DIGEST_LEN) -> str:
    joined = _FIELD_SEP.join(_canonical(part) for part in parts)
    return hashlib.sha256(joined.encode("utf-8")).hexdigest()[:length]


def derive_id(prefix: str, *parts: object, length: int = _DIGEST_LEN) -> str:
    """Generic ``"{prefix}_{sha256(parts)[:length]}"`` stable id.

    Stages that need an id not covered by a dedicated helper (e.g. ad-hoc audit
    refs) can call this directly. Pass the *identity-bearing* inputs only.
    """
    return f"{prefix}_{_digest(*parts, length=length)}"


# --- Ingestion ids ---------------------------------------------------------


def piece_id(source_id: str, order_index: int) -> str:
    """Return ``"{source_id}:{order_index:06d}"``."""
    return f"{source_id}:{order_index:06d}"


def window_id(source_id: str, piece_ids: Iterable[str]) -> str:
    """Derived from source + the (ordered) packed piece ids.

    Re-packing pieces into different windows changes ``window_id`` (grouping is
    the window's identity) while leaving each ``piece_id`` untouched.
    """
    return derive_id("win", source_id, list(piece_ids))


def atom_id(
    source_id: str,
    piece_refs: Iterable[str],
    source_material_ids: Iterable[str] = (),
) -> str:
    """Derived from source + global piece refs + optional lineage.

    Excludes ``content_kind`` (and every other volatile label). ``piece_refs``
    are ordered (content is rebuilt from pieces in order). ``source_material_ids``
    is the lineage for run-scoped condensed material; empty for stable atoms.
    """
    return derive_id("atom", source_id, list(piece_refs), list(source_material_ids))


def name_resolution_rule_id(
    project_id: str,
    aliases: Iterable[str],
    evidence_chunk_ids: Iterable[str],
) -> str:
    """Derive one name-table rule id without coupling it to the chosen surface."""

    return derive_id(
        "namerule",
        project_id,
        sorted(aliases),
        sorted(evidence_chunk_ids),
    )


def name_resolution_plan_id(
    project_id: str,
    output_language: str,
    input_hash: str,
    contract_ids: Iterable[str],
    resolved_rows: Iterable[object],
) -> str:
    """Derive a plan id from exact inputs and final render-visible rules."""

    return derive_id(
        "nameresolution",
        project_id,
        output_language,
        input_hash,
        list(contract_ids),
        list(resolved_rows),
    )


# --- Planning / Selection ids ----------------------------------------------


def candidate_id(
    project_id: str,
    material_ids: Iterable[str],
    source_material_ids: Iterable[str] = (),
) -> str:
    """Derived from project + ordered material refs + optional lineage.

    Excludes ``narrative_function`` and every other volatile label.
    """
    return derive_id("cand", project_id, list(material_ids), list(source_material_ids))


def graph_id(project_id: str, candidate_ids: Iterable[str] = ()) -> str:
    """Candidate graph id, derived from project + ordered candidate ids."""
    return derive_id("graph", project_id, list(candidate_ids))


def selection_plan_id(
    project_id: str,
    persona_id: str,
    selected_sequence: Iterable[str],
) -> str:
    """Selection plan id, derived from project + persona + the ordered path."""
    return derive_id("selplan", project_id, persona_id, list(selected_sequence))


# --- Node Edit / Packing ids -----------------------------------------------


def node_edit_plan_id(
    project_id: str,
    selection_plan_id: str,
    candidate_graph_id: str,
) -> str:
    """Node edit plan id, derived from its upstream plan/graph ids."""
    return derive_id("nedit", project_id, selection_plan_id, candidate_graph_id)


def chunk_plan_id(
    project_id: str,
    selection_plan_id: str,
    node_edit_plan_id: str,
) -> str:
    """Chunk plan id, derived from project + selection plan + node edit plan."""
    return derive_id("chunkplan", project_id, selection_plan_id, node_edit_plan_id)


def chunk_id(project_id: str, order_index: int, node_ids: Iterable[str]) -> str:
    """Chunk id, derived from project + order index + the ordered node ids."""
    return derive_id("chunk", project_id, order_index, list(node_ids))


def contract_id(project_id: str, chunk_id: str) -> str:
    """Render contract id (1:1 with a chunk)."""
    return derive_id("contract", project_id, chunk_id)


# --- Reporting ids ---------------------------------------------------------


def issue_id(
    stage: str,
    kind: str,
    artifact_ref: str | None = None,
    message: str | None = None,
) -> str:
    """Deterministic audit-issue id from its identifying fields."""
    return derive_id("issue", stage, kind, artifact_ref or "", message or "")


def new_call_id() -> str:
    """Fresh, non-deterministic id for one provider attempt (uuid-based)."""
    return f"call_{uuid.uuid4().hex}"


# --- Call-local aliases ----------------------------------------------------


@dataclass(frozen=True)
class AliasScheme:
    """A call-local alias format: a ``prefix`` plus a zero-padded number.

    ``width`` is the minimum digit width (``0`` means no padding). Numbers wider
    than ``width`` are emitted in full, so ``width`` is a floor, not a ceiling.
    """

    prefix: str
    width: int = 0

    def format(self, number: int) -> str:
        if number < 0:
            raise ValueError("alias number must be non-negative")
        if self.width:
            return f"{self.prefix}{number:0{self.width}d}"
        return f"{self.prefix}{number}"

    def parse(self, alias: str) -> int:
        if not alias.startswith(self.prefix):
            raise ValueError(f"alias {alias!r} does not match prefix {self.prefix!r}")
        body = alias[len(self.prefix):]
        if not body.isdigit():
            raise ValueError(f"alias {alias!r} has a non-numeric body")
        return int(body)


# Standard call-local projection schemes.
PIECE_ALIASES = AliasScheme("p", 4)
MATERIAL_ALIASES = AliasScheme("M", 3)
CANDIDATE_ALIASES = AliasScheme("C", 3)
NODE_ALIASES = AliasScheme("N", 1)
RENDER_ALIASES = AliasScheme("R", 3)


class AliasManifest:
    """Bidirectional map between call-local aliases and global stable ids.

    Mint aliases in projection order (``mint``/``number``); hand the aliases to
    the model; expand the model's output back to global ids with ``resolve``.
    ``mint`` is idempotent per global id (a global id always maps to one alias
    within a manifest). The manifest is *not* persisted -- only the global ids it
    resolves to are.
    """

    def __init__(self, scheme: AliasScheme, *, start: int = 1) -> None:
        self.scheme = scheme
        self._next = start
        self._by_global: dict[str, str] = {}
        self._by_alias: dict[str, str] = {}

    def mint(self, global_id: str) -> str:
        existing = self._by_global.get(global_id)
        if existing is not None:
            return existing
        alias = self.scheme.format(self._next)
        self._next += 1
        self._by_global[global_id] = alias
        self._by_alias[alias] = global_id
        return alias

    def alias_for(self, global_id: str) -> str:
        try:
            return self._by_global[global_id]
        except KeyError:
            raise KeyError(f"no alias minted for global id {global_id!r}") from None

    def resolve(self, alias: str) -> str:
        # Validate shape first so malformed aliases fail clearly, then look up.
        self.scheme.parse(alias)
        try:
            return self._by_alias[alias]
        except KeyError:
            raise KeyError(f"alias {alias!r} is not in this manifest") from None

    def items(self) -> list[tuple[str, str]]:
        """``(alias, global_id)`` pairs in mint order."""
        return list(self._by_alias.items())

    def __contains__(self, item: str) -> bool:
        return item in self._by_alias or item in self._by_global

    def __len__(self) -> int:
        return len(self._by_alias)

    @classmethod
    def number(
        cls,
        scheme: AliasScheme,
        global_ids: Iterable[str],
        *,
        start: int = 1,
    ) -> AliasManifest:
        """Build a manifest by minting ``global_ids`` in order."""
        manifest = cls(scheme, start=start)
        for global_id in global_ids:
            manifest.mint(global_id)
        return manifest
